CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    password VARCHAR(255),
    role VARCHAR(255),
    email VARCHAR(255),
    full_name VARCHAR(255),
    phone VARCHAR(255),
    nic VARCHAR(255),
    salary DOUBLE PRECISION,
    join_date DATE,
    status VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(255) UNIQUE,
    email VARCHAR(255),
    address VARCHAR(255),
    birthday DATE,
    loyalty_points INTEGER DEFAULT 0,
    total_spending DOUBLE PRECISION DEFAULT 0,
    total_orders INTEGER DEFAULT 0,
    membership_level VARCHAR(255),
    registration_date TIMESTAMP WITHOUT TIME ZONE,
    last_purchase_date TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code VARCHAR(255) UNIQUE,
    company_name VARCHAR(255) NOT NULL,
    contact_person VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    address VARCHAR(255),
    payment_terms VARCHAR(255),
    category VARCHAR(255),
    status VARCHAR(255),
    total_purchase_value DOUBLE PRECISION DEFAULT 0,
    last_delivery_date TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(255),
    category VARCHAR(255),
    unit_type VARCHAR(255),
    stock_quantity DOUBLE PRECISION,
    minimum_stock_level DOUBLE PRECISION,
    buying_price DOUBLE PRECISION,
    selling_price DOUBLE PRECISION,
    discount_percentage DOUBLE PRECISION,
    manufacturing_date DATE,
    expiry_date DATE,
    supplier_id BIGINT,
    supplier_name VARCHAR(255),
    barcode VARCHAR(255),
    brand VARCHAR(255),
    batch_number VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(255) NOT NULL,
    category VARCHAR(255),
    stock_quantity DOUBLE PRECISION NOT NULL,
    minimum_stock_level DOUBLE PRECISION,
    buying_price DOUBLE PRECISION,
    selling_price DOUBLE PRECISION,
    unit_type VARCHAR(255),
    location VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_number VARCHAR(255) NOT NULL UNIQUE,
    cashier_name VARCHAR(255),
    customer_id BIGINT,
    customer_name VARCHAR(255),
    subtotal DOUBLE PRECISION,
    discount_amount DOUBLE PRECISION,
    total_amount DOUBLE PRECISION,
    received_amount DOUBLE PRECISION,
    balance DOUBLE PRECISION,
    investment DOUBLE PRECISION,
    status VARCHAR(255),
    payment_method VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS bill_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT,
    product_name VARCHAR(255),
    category VARCHAR(255),
    unit_price DOUBLE PRECISION,
    buying_price DOUBLE PRECISION,
    quantity INTEGER,
    discount_percentage DOUBLE PRECISION,
    bill_id BIGINT REFERENCES bills (id)
);

